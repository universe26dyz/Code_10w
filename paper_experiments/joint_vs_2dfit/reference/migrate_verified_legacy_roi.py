"""Explicitly migrate a Phase-0.6 verified legacy ROI without interpolation."""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path
from typing import Any

import nibabel as nib
import numpy as np


REPO_ROOT = Path(__file__).resolve().parents[3]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from evaluation_common.myocardium.build_native_bundle import build_bundle
from evaluation_common.myocardium.legacy_masks import classify_affine_relation, reorient_labels_exact
from paper_experiments.joint_vs_2dfit.audit._common import sha256


REUSABLE = {"reusable_exact", "reusable_with_deterministic_transform"}


def validate_migration_request(report: dict[str, Any], subject_id: str, destination: str | Path) -> dict[str, Any]:
    try:
        entry = report["subjects"][subject_id]
    except KeyError as exc:
        raise ValueError(f"Subject {subject_id} is absent from the compatibility report") from exc
    if entry["compatibility"]["status"] not in REUSABLE:
        raise ValueError(f"Subject {subject_id} is not verified reusable")
    target = Path(destination)
    if target.exists():
        raise FileExistsError(f"Refusing to overwrite existing destination: {target}")
    return entry


def _round_trip_check(legacy_roi: dict[str, Any]) -> dict[str, bool]:
    composite = nib.load(legacy_roi["composite_reference"]["path"])
    result: dict[str, bool] = {}
    for name, record in legacy_roi["manual_masks"].items():
        source = nib.load(record["path"])
        relation = legacy_roi["geometry_relations_to_composite"][name]
        mapped = reorient_labels_exact(np.asanyarray(source.dataobj), relation, composite.shape)
        inverse = classify_affine_relation(composite.affine, source.affine, composite.shape, source.shape)
        restored = reorient_labels_exact(mapped, inverse, source.shape)
        result[name] = bool(np.array_equal(restored, np.asanyarray(source.dataobj)))
    if not all(result.values()):
        raise ValueError("Legacy label round-trip check failed")
    return result


def migrate_verified_legacy_roi(*, compatibility_report: Path, subject_id: str, prepared_sax: Path, native_reference: Path, destination: Path, repo: Path) -> Path:
    report = json.loads(compatibility_report.read_text(encoding="utf-8"))
    entry = validate_migration_request(report, subject_id, destination)
    legacy_roi = entry["legacy_roi"]
    round_trip = _round_trip_check(legacy_roi)
    with tempfile.TemporaryDirectory(prefix="phase0_6_legacy_roi_") as temporary:
        audit_path = Path(temporary) / "legacy_roi_geometry.json"
        audit_path.write_text(json.dumps({subject_id: legacy_roi}), encoding="utf-8")
        output = build_bundle(
            subject_id=subject_id,
            audit_json=audit_path,
            prepared_sax=prepared_sax,
            native_reference=native_reference,
            output=destination,
            repo=repo,
        )
    manifest_path = output / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["phase0_6_migration_provenance"] = {
        "compatibility_report": {"path": str(compatibility_report.resolve()), "sha256": sha256(compatibility_report)},
        "compatibility_status": entry["compatibility"]["status"],
        "legacy_source_dicom": entry["legacy_source_dicom"],
        "current_source_dicom": entry["current_source_dicom"],
        "source_dicom_comparison": entry["source_dicom_comparison"],
        "raw_data_identity": entry["raw_data_identity"],
        "geometry_chain": entry["geometry_chain"],
        "round_trip_exact": round_trip,
        "interpolation": "nearest-neighbor only; implementation permits only exact transpose/flip and integer crop",
        "overlay_qc": "qc_all_slices generated by build_bundle against the explicit native reference",
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compatibility-report", required=True, type=Path)
    parser.add_argument("--subject-id", required=True)
    parser.add_argument("--prepared-sax", required=True, type=Path)
    parser.add_argument("--native-reference", required=True, type=Path)
    parser.add_argument("--destination", required=True, type=Path)
    parser.add_argument("--repo", default=REPO_ROOT, type=Path)
    args = parser.parse_args()
    print(migrate_verified_legacy_roi(**vars(args)))


if __name__ == "__main__":
    main()
